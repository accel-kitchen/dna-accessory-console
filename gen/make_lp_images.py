"""Render the 3D images of the landing-page mock-up (lp/) from the current PCB and fix the LED overlay mapping.

Needs Pillow and kicad-cli (KiCad 9).  Run:  python gen/make_lp_images.py [--quality high|basic]
Writes lp/assets/img/{board-top,board-tilt,collar-front,collar-back}.png and rewrites the generated block
(LEDS table + image mapping) in lp/assets/js/main.js and the aspect ratio in lp/assets/css/style.css.
"""
import csv, json, re, subprocess, sys, tempfile
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
KCLI = r'C:\Program Files\KiCad\9.0\bin\kicad-cli.exe'
PCB = str(ROOT / 'dna-accesories.kicad_pcb')
IMG = ROOT / 'lp' / 'assets' / 'img'
QUALITY = sys.argv[sys.argv.index('--quality') + 1] if '--quality' in sys.argv else 'high'
TOP_W = 984                                   # width of board-top.png in px (board edge to board edge)


def render(name, size, *args):
    out = Path(tempfile.gettempdir()) / f'lp_{name}.png'
    subprocess.run([KCLI, 'pcb', 'render', '--quality', QUALITY, '--background', 'transparent',
                    '--width', str(size[0]), '--height', str(size[1]), *args, '-o', str(out), PCB],
                   check=True, capture_output=True)
    return Image.open(out).convert('RGBA')


def crop_alpha(im, pad=0, solid=200):
    # only (nearly) opaque pixels count: the ray-traced render adds faint shadows around the board
    box = im.getchannel('A').point(lambda a: 255 if a > solid else 0).getbbox()
    return im.crop((box[0] - pad, box[1] - pad, box[2] + pad, box[3] + pad)), box


geom = json.loads((ROOT / 'design' / 'dna-geometry.json').read_text(encoding='utf-8'))
bx0, by0, bx1, by1 = geom['bounds']
BW = bx1 - bx0

# ---- top view: board edge to board edge = TOP_W px, top edge of the board = row 0.
# The ray-traced ('high') render keeps the board outline but not the x/y pixel ratio of the viewport, so the
# cropped board is resized to its true proportion (the alpha box of the top view is exactly the board outline).
big, _ = crop_alpha(render('top', (3200, 4800), '--side', 'top', '--zoom', '0.6'))
top = big.resize((TOP_W, round(TOP_W * (by1 - by0) / BW)), Image.LANCZOS)
top.save(IMG / 'board-top.png', optimize=True)
print('board-top', top.size, 'from', big.size)

# ---- oblique views
tilt, _ = crop_alpha(render('tilt', (2400, 2400), '--rotate', ' -55,0,32', '--perspective', '--zoom', '0.8'), 6)
tilt.thumbnail((1000, 1000), Image.LANCZOS)
tilt.save(IMG / 'board-tilt.png', optimize=True)
print('board-tilt', tilt.size)
for side, name, angles in (('top', 'collar-front', ' -50,0,25'), ('bottom', 'collar-back', ' -50,0,-25')):
    im, _ = crop_alpha(render(name, (2400, 1800), '--side', side, '--rotate', angles, '--perspective',
                              '--zoom', '1.9', '--pivot', ' 0,-2.4,0'), 6)   # pivot = collar centre (cm from board centre)
    im.thumbnail((1100, 1100), Image.LANCZOS)
    im.save(IMG / f'{name}.png', optimize=True)
    print(name, im.size)

# ---- overlay mapping for lp/assets/js/main.js
rows = list(csv.DictReader((ROOT / 'design' / 'base-pairs.csv').open(encoding='utf-8-sig', newline='')))
leds = ',\n    '.join(
    ','.join(f"['{r['reference']}',{r['pair']},'{r['strand']}',{float(r['x_mm']):g},{float(r['y_mm']):g}]"
             for r in rows[i:i + 4]) for i in range(0, len(rows), 4))
y0 = geom['helix_start_y']; pitch = geom['pair_pitch_mm']
block = f'''/* generated by gen/make_lp_images.py: do not edit by hand */
  var LEDS = [
    {leds}
  ];
  // board outline (Edge.Cuts) <-> 3D render board-top.png ({top.width}x{top.height}px, cropped to the board)
  var BX0 = {bx0:g}, BW = {BW:g}, BY0 = {by0:.4f};
  var PX_PER_MM = {top.width} / BW, IMG_W = {top.width}, IMG_H = {top.height}, IMG_TOP = 0;
  var PAIR_Y0 = {y0:.4f}, PAIR_PITCH = {pitch:g};   // first base-pair row and row pitch (mm)
  function xPct(x) {{ return (x - BX0) / BW * 100; }}
  function yPct(y) {{ return (IMG_TOP + (y - BY0) * PX_PER_MM) / IMG_H * 100; }}
  /* end generated */'''
js_path = ROOT / 'lp' / 'assets' / 'js' / 'main.js'
js = js_path.read_text(encoding='utf-8')
if '/* generated by gen/make_lp_images.py' in js:
    js = re.sub(r'/\* generated by gen/make_lp_images\.py.*?/\* end generated \*/', lambda m: block, js, flags=re.S)
else:
    a = js.index('  // [基板参照')
    z = js.index('  var COLOR')
    js = js[:a] + '  // [ref, pair no., strand (A=sense / B=complement), X mm, Y mm]  ordered as the DIN->DOUT data chain\n  ' + block + '\n\n' + js[z:]
js = js.replace('var y1 = yPct(40 + k * 19.5) - 1.1, y2 = yPct(40 + k * 19.5 + 13) + 1.1;',
                'var y1 = yPct(PAIR_Y0 + k * 3 * PAIR_PITCH) - 1.1, y2 = yPct(PAIR_Y0 + (k * 3 + 2) * PAIR_PITCH) + 1.1;')
js_path.write_text(js, encoding='utf-8')
css_path = ROOT / 'lp' / 'assets' / 'css' / 'style.css'
css = css_path.read_text(encoding='utf-8')
css = re.sub(r'aspect-ratio:984/\d+', f'aspect-ratio:{top.width}/{top.height}', css)
css_path.write_text(css, encoding='utf-8')
print('mapping updated: board', (bx0, by0), 'width', BW, 'img', top.size)
