"""Generate console/board-data.js from the real design data.

Inputs : design/dna-geometry.json (outline, holes), design/base-pairs.csv (LED positions)
Output : console/board-data.js  (window.BOARD)

Run from the repository root:  python console/tools/make_board_data.py
"""
import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
GEOM = ROOT / "design" / "dna-geometry.json"
PAIRS = ROOT / "design" / "base-pairs.csv"
OUT = ROOT / "console" / "board-data.js"


def ring_path(points):
    pts = [f"{x:.2f} {y:.2f}" for x, y in points]
    return "M" + " L".join(pts) + " Z"


def main():
    geom = json.loads(GEOM.read_text(encoding="utf-8"))
    leds = []
    with PAIRS.open(encoding="utf-8-sig", newline="") as f:
        for i, row in enumerate(csv.DictReader(f)):
            ref = row["reference"]
            # chain order must equal pixel order: U2 = pixel 0 ... U25 = pixel 23
            assert int(ref[1:]) - 2 == i, f"chain order broken at {ref}"
            pair = int(row["pair"]) - 1
            assert i // 2 == pair, f"pair mapping broken at {ref}"
            assert row["strand"] == ("A" if i % 2 == 0 else "B"), f"strand broken at {ref}"
            leds.append({
                "ref": ref,
                "pair": pair,
                "codon": int(row["group"]) - 1,
                "strand": row["strand"],
                "x": round(float(row["x_mm"]), 3),
                "y": round(float(row["y_mm"]), 3),
                "base": row["base"],
            })
    assert len(leds) == 24

    data = {
        "bounds": [round(v, 2) for v in geom["bounds"]],
        "outer": ring_path(geom["outer"]),
        "holes": [ring_path(h) for h in geom["holes"]],
        "leds": leds,
        # 5'-ATG GCA TCG TAA-3' (strand A, from the silkscreen CSV)
        "defaultSeq": "".join(l["base"] for l in leds if l["strand"] == "A"),
    }
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(
        "// Generated by console/tools/make_board_data.py from design/ - do not edit by hand.\n"
        "window.BOARD = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print("wrote", OUT, "default sequence", data["defaultSeq"])


if __name__ == "__main__":
    main()
